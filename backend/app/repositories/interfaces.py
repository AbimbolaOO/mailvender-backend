"""Repository interfaces used by the application services.

Services depend only on these protocols (through `UnitOfWork`); the SQLAlchemy
implementations in `sql.py` are the only code that performs persistence.
Entities are the mapped classes in `app.models`; changes made to an entity
returned by a repository are persisted when the unit of work commits.
"""

import uuid
from collections.abc import Iterable, Sequence
from datetime import date, datetime
