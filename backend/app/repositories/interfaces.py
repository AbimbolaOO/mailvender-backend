    @property
    def suppressions(self) -> SuppressionRepository: ...

    @property
    def audit(self) -> AuditRepository: ...

    @property
    def rate_limits(self) -> RateLimitRepository: ...

    @property
    def sync(self) -> SyncRepository: ...

    @property
    def exports(self) -> ExportRepository: ...

    @property
    def jobs(self) -> JobRepository: ...

    @property
    def admins(self) -> AdminRepository: ...

    @property
    def admin_issues(self) -> AdminIssueRepository: ...

    @property
    def inbound(self) -> InboundRepository: ...

    @property
    def admin_stats(self) -> AdminStatsRepository: ...

    @property
    def admin_mail(self) -> AdminMailRepository: ...

    @property
    def system_state(self) -> SystemStateRepository: ...

    @property
    def webhooks(self) -> WebhookRepository: ...

    @property
    def starter_templates(self) -> StarterTemplateRepository: ...


    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def savepoint(self) -> Any: ...
